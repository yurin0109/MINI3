# 5-1 (가설 2 - 대책 타임라인): plt.scatter(x=날짜, y=대책유형) 으로 사례 1건을 점 1개로 그린다.
#                              (수업 참고: day09/g-01.py 3번 산점도) → 이동권·대중교통 점이 2024년에 처음 나오면 가설 2 채택
plt.figure(figsize=(10, 5))
plt.scatter(최종['날짜'], 최종['대책유형'])
plt.title('2022~2024년 고령자 교통대책 타임라인')
plt.xlabel('날짜')
plt.ylabel('대책유형')
plt.grid(True)
plt.show()
# 5-2 (가설 1 - 유형별 사례 수): value_counts() 로 대책유형별 사례 수를 구해 막대 그래프 + bar_label 로 그린다.
#                               (수업 참고: day09/g-01.py 2번 막대 차트 + bar_label)
#                               → (운전자·차량 + 면허·적성) > 이동권·대중교통 이면 가설 1 채택
유형별 = 최종['대책유형'].value_counts()
plt.figure(figsize=(9, 5))
bars = plt.bar(유형별.index, 유형별)
plt.bar_label(bars, padding=3)
plt.title('고령자 교통대책 유형별 사례 수')
plt.xlabel('대책유형')
plt.ylabel('사례 수')
plt.show()
# 가설1 건수 비교
운전자 = len(최종[최종['대책유형'] == '운전자·차량'])
면허 = len(최종[최종['대책유형'] == '면허·적성'])
이동권 = len(최종[최종['대책유형'] == '이동권·대중교통'])

print("운전자·차량 + 면허·적성:", 운전자 + 면허)
print("이동권·대중교통:", 이동권)

if 운전자 + 면허 > 이동권:
    print("가설 1: 수집된 사례에서는 예상과 일치")
else:
    print("가설 1: 수집된 사례에서는 예상과 불일치")

# 5-3 (보조 분석): value_counts() 로 부처별 사례 수를 확인한다. (어느 부처가 고령자 교통 대책을 주로 발표하는가)
print("부처별 사례 수:")
print(최종['부처'].value_counts())
