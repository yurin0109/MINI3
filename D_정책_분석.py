import pandas as pd
import matplotlib.pyplot as plt

plt.rc('font', family='Malgun Gothic')
plt.rcParams['axes.unicode_minus'] = False

# 4-5 (사례 묶기): 같은 날·같은 부처의 보도자료와 정책뉴스는 같은 대책이므로 1개 사례로 묶는다. (이중 집계 방지)
#                  (힌트: '제외' 를 뺀 뒤 drop_duplicates(['날짜', '부처', '대책유형']) ) → 최종 약 7건
분류결과 = pd.read_csv('정책브리핑_분류완료.csv', encoding='cp949')
print("분류된 전체 기사 수:", len(분류결과))

print("실제 CSV 컬럼명:", 분류결과.columns)
print("대책유형별 건수:", 분류결과['대책유형'].value_counts())

# 분류명 앞뒤에 공백 제거하고 통일
분류결과['대책유형'] = 분류결과['대책유형'].fillna('').str.strip()
분류결과.loc[분류결과['대책유형'] == '보행환경', '대책유형'] = '보행 환경'
분류결과.loc[분류결과['대책유형'] == '이동권,대중교통', '대책유형'] = '이동권·대중교통'

# 분류 끝나지 않은 기사 확인
미확정 = 분류결과[(분류결과['대책유형'] == '') | (분류결과['대책유형'] == '검토필요')]
print("미확정 기사 수:", len(미확정))
print(미확정[['제목', '대책유형']])

# 제외 기사 제거
사례 = 분류결과[분류결과['대책유형'] != '제외'].copy()
print("제외 후 기사 수:", len(사례))
print(사례[['날짜', '부처', '제목', '대책유형', '종류']])

# 동일 정책의 보도자료와 정책뉴스 중복제거 / 23-11-29 와 24-10-14 중복
사례 = 사례[사례['제목'] != '보행자 사망 중 노인 절반 이상…사고 고위험 지점 정비한다']
사례 = 사례[사례['제목'] != '경찰·지자체·자동차업계, 고령자 ‘수요응답형 버스’ 도입 촉진 나서']
사례 = 사례.reset_index(drop=True)
print("중복 정리 후 사례 수:", len(사례))

# 4-6 (형변환 - 날짜): pd.to_datetime 으로 날짜를 객체화하고 .dt.year 로 '연도' 열을 만든다. (수업 참고: day08/p-02.py 9번)
사례['날짜'] = pd.to_datetime(사례['날짜'])
사례['연도'] = 사례['날짜'].dt.year
print("연도별 사례 수:")
print(사례['연도'].value_counts())
# 4-7 (결측치 처리): 요약이 비어 있는 보도자료는 제목만으로 분류하고 그 사실을 기록한다. (임의로 채우지 않는다)
사례['요약확인'] = '정상'
사례.loc[사례['요약'].fillna('').str.strip() == '', '요약확인'] = '요약 없음(제목 확인 필요)'
print("요약이 없는 사례:")
print(사례[사례['요약확인'] != '정상'][['제목', '요약확인']])
print("날짜 결측 수:")
print(사례['날짜'].isnull().sum())
# 4-8 (저장): 사례번호, 날짜, 연도, 부처, 제목, 대책유형, 종류, 링크 컬럼을 data/clean/정제_D_정책.csv 로 저장한다.
사례['사례번호'] = range(1, len(사례) + 1)
최종 = 사례[['사례번호', '날짜', '연도', '부처', '제목', '대책유형', '종류', '링크']]

최종.to_csv('data/clean/정제_D_정책.csv', index=False, encoding='utf-8-sig')
사례.to_csv('data/clean/정책_검토기록.csv', index=False, encoding='utf-8-sig')

print("최종 사례 수:", len(최종))
print(최종[['사례번호', '날짜', '제목', '대책유형']])
print("최종 CSV 저장 완료")
