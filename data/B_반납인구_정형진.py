#                   df.columns = df.columns.str.replace('2022년12월_계_', '') 처럼 연도 부분을 지워 세 파일의 컬럼명을 같게 만든다.
#                   → '총인구수', '0~4세', … '100세 이상' 처럼 짧아진다.

# 4-2 (행 정리 · 연도 열): 각 파일에서 첫 행 '전국' 은 시도가 아니므로 제거한다. (남기면 합계가 두 번 들어가 평균·상관이 왜곡된다)
#                         행정구역 "서울특별시  (1100000000)" 은 str.split('(').str[0].str.strip() 으로 이름만 남겨 '시도명' 열을 만든다.
#                         각 파일에 '연도' 열(2022·2023·2024)을 넣은 뒤 pd.concat 으로 세로 연결한다. (수업 참고: day08/p-01.py 14번 concat)
#                         → 17개 시도 × 3년 = 51행

인구목록 = []
for 연도 ,df in [(2022, 인구22) , (2023, 인구23) , (2024 , 인구24)]:
    df = df.copy()
    df.columns = df.columns.str.replace(f'{연도}년12월_계_', '')
    df = df[~df['행정구역'].str.startswith('전국')]
    df['시도명'] = df['행정구역'].str.split('(').str[0].str.strip()
    df['연도'] = 연도
    인구목록.append(df)

인구 = pd.concat(인구목록 , ignore_index=True)
print("컬럼명:" ,list(인구.columns[:5]) , '...')
print('전국 제거 + 3년 세로 연결 후 :' , 인구.shape)


# 4-3 (형변환): 인구 수치는 "9,331,828" 처럼 쉼표가 있는 문자열이므로 str.replace(',', '') 후 pd.to_numeric 으로 숫자형으로 변환한다.
#               (수업 참고: day10/Practice6.py 4-3 형변환)
나이컬럼 = ['65~69세', '70~74세', '75~79세', '80~84세', '85~89세', '90~94세', '95~99세', '100세 이상']
