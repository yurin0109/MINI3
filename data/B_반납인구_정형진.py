# 4-5 (연도별 명칭 통일)
통일전_이름 = 인구.groupby('연도')['시도명'].unique()                    # 6-3 기록용으로 보관
인구['시도명'] = 인구['시도명'].replace({'강원도': '강원특별자치도', '전라북도': '전북특별자치도'})
