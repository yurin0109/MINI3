print('\n[4-3] 변환 전 자료형:', 인구['총인구수'].dtype)
for col in 숫자컬럼:
    인구[col] = pd.to_numeric(인구[col].astype(str).str.replace(',', ''), errors='coerce')
print('변환 후 자료형:', 인구['총인구수'].dtype, '/ 변환 실패(NaN):', 인구[숫자컬럼].isnull().sum().sum(), '건')


# 4-4 (파생변수): 65세 이상 인구, 고령화율
인구['65세이상인구'] = 인구[나이컬럼].sum(axis=1)
인구['고령화율'] = 인구['65세이상인구'] / 인구['총인구수'] * 100
