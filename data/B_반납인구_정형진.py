# 4-8 (그룹화 합산): 경기남부 + 경기북부 → 경기도
반납 = 반납.groupby('시도명', as_index=False)[반납열].sum()
print('[4-8] 경기 합산 후:', 반납.shape, '(18행 → 17행)')

# 4-9 (세로로 쌓기)
반납목록 = []
for 연도 in [2022, 2023, 2024]:
    t = 반납[['시도명', f'{연도} 65세 이상']].rename(columns={f'{연도} 65세 이상': '반납건수'})
    t['연도'] = 연도
    반납목록.append(t)
반납_세로 = pd.concat(반납목록, ignore_index=True)
print('[4-9] 세로로 쌓은 후:', 반납_세로.shape)                           # (51, 3)

# 4-10 (결측치 확인)
print('\n[4-10] 결측치 확인')
print('인구:', 인구[['시도명', '연도'] + 숫자컬럼].isnull().sum().sum(), '건 / 반납:', 반납_세로.isnull().sum().sum(), '건')

# 4-11 (병합)
뼈대 = pd.merge(인구, 반납_세로, on=['연도', '시도명'], how='left')
print('\n[4-11] 병합 후:', 뼈대.shape, '/ 반납건수 결측:', 뼈대['반납건수'].isnull().sum(), '건')

# 4-12 (파생변수 - 반납률): 65세 이상 인구 천 명당 반납 건수
뼈대['반납률'] = 뼈대['반납건수'] / 뼈대['65세이상인구'] * 1000

# 4-13 (검증 · 저장)
뼈대 = 뼈대[['연도', '시도명', '총인구수', '65세이상인구', '고령화율', '반납건수', '반납률']]
뼈대 = 뼈대.sort_values(['연도', '시도명']).reset_index(drop=True)
print('\n[4-13] 최종 뼈대:', 뼈대.shape, '(기대: (51, 7))')
print(뼈대.isnull().sum())
