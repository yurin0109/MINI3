#         → 정류장은 많지만 반납률이 낮은 도 지역 = 수요응답형 버스 우선 지역

# 5-7 (융화 인사이트) - D 결과로 채우기
#   예) "데이터는 정류장 수가 아니라 버스 서비스 수준이 반납과 관련 있음을 시사하는데,
#        정부 대책은 ○○ 유형이 중심이었고, 이동권(수요응답형 버스) 대책은 2024년(경찰청 2024.10.14)에야 등장했다."


# [6. 비즈니스 임팩트 계산 (전략적 제언용) - 2024년 기준]
y24 = 합계[합계['연도'] == 2024].copy()
전국반납률 = y24['반납건수'].sum() / y24['65세이상인구'].sum() * 1000      # 평균 X, 합산 후 재계산
print(f'\n[6] 2024년 전국 반납률: {전국반납률:.2f}')

# 6-1 (힌트 기준): 정류장_천명당 하위 1/3 시도
하위 = y24.nsmallest(len(y24) // 3, '정류장_천명당').copy()
하위['추가반납자'] = (전국반납률 - 하위['반납률']).clip(lower=0) * 하위['65세이상인구'] / 1000
print('\n[6-1 힌트 기준] 정류장_천명당 하위 1/3 시도')
print(하위[['시도명', '정류장_천명당', '반납률', '추가반납자']].round(2).to_string(index=False))
print('  추가 반납자 합계:', round(하위['추가반납자'].sum()), '명  ← 대부분 이미 평균보다 높아 효과가 거의 없음')

# 6-1 (결과 반영안): 반납률 하위 1/3 시도를 전국 평균까지 올린다고 가정
대상 = y24.nsmallest(len(y24) // 3, '반납률').copy()
대상['추가반납자'] = (전국반납률 - 대상['반납률']) * 대상['65세이상인구'] / 1000
print('\n[6-1 결과 반영안] 반납률 하위 1/3 시도')
print(대상[['시도명', '정류장_천명당', '반납률', '추가반납자']].round(2).to_string(index=False))
print('  추가 반납자 합계:', round(대상['추가반납자'].sum()), '명')

# 6-2 (감소 사고 건수)
대상['감소사고'] = 대상['추가반납자'] * 대상['고령사고_만명당'] / 10000
감소사고 = 대상['감소사고'].sum()
print(f'\n[6-2] 감소 사고 건수(추정): 약 {감소사고:.1f}건')

# 6-3 (절감액): 사고 1건당 사회적 비용 - 출처를 확인해 팀에서 기준을 정한 뒤 숫자로 입력 (단위: 원)
#   참고(도로교통공단, 2022년 기준 · 2024.02 발표): 사망 1명 5억 3,379만 원 / 중상 6,890만 원 / 경상 520만 원
사고1건당_비용 = None
if 사고1건당_비용:
    절감액 = 감소사고 * 사고1건당_비용
    print(f'[6-3] 절감액(추정): 약 {절감액 / 1e8:.1f}억 원')
    # 6-4 (비용 비교): 농촌형 교통모델 지원액 군당 3.5억 원
    print(f'[6-4] 농촌형 교통모델 지원(군당 3.5억 원) 약 {절감액 / 3.5e8:.1f}개 군 규모')
else:
    print('[6-3] 사고 1건당 사회적 비용을 정한 뒤 다시 실행')

