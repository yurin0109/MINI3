# ※ 추정치이므로 보고서에는 "약 ○○억 원으로 추정된다" 처럼 가정과 함께 쓴다.
# ※ 한계: 군위군 대구 편입(2023.7)은 모든 데이터에서 옮기지 않고 각 연도 당시 행정구역 그대로 썼다.

# 1. 파일 위치
A파일 = './data/정제_A_사고.csv'
B파일 = './data/정제_B_반납인구.csv'
C파일 = './data/정제_C_정류장.csv'

저장폴더 = './data/merge'
그래프폴더 = './data/graphs'
os.makedirs(저장폴더, exist_ok=True)
os.makedirs(그래프폴더, exist_ok=True)

# 2. 데이터 불러오기
A = pd.read_csv(A파일, encoding='utf-8-sig')
B = pd.read_csv(B파일, encoding='utf-8-sig')
C = pd.read_csv(C파일, encoding='utf-8-sig')
print('[1] 데이터 행 수  A:', len(A), '/ B:', len(B), '/ C:', len(C), '(모두 51 이어야 함)')
print('    A 파일 위치:', A파일)

# 3. 결합에 필요한 열만 고르기 (겹치는 65세이상인구 등은 빼고)
A = A[['연도', '시도명', '고령사고_만명당']].copy()
C = C[['연도', '시도명', '전체버스정류장']].copy()

for 자료 in [A, B, C]:
    자료['연도'] = pd.to_numeric(자료['연도'])
    자료['시도명'] = 자료['시도명'].replace({'강원도': '강원특별자치도', '전라북도': '전북특별자치도', '제주도': '제주특별자치도'})

for 이름, 자료 in [('A', A), ('B', B), ('C', C)]:
    if 자료.duplicated(['연도', '시도명']).any():
        raise ValueError(이름 + ' 파일에 연도·시도 중복이 있습니다.')


# [4. 데이터 결합]
# 4-1 (병합)
합계 = pd.merge(B, A, on=['연도', '시도명'], how='left')
합계 = pd.merge(합계, C, on=['연도', '시도명'], how='left')
합계['정류장_천명당'] = 합계['전체버스정류장'] / 합계['65세이상인구'] * 1000   # C 와 같은 계산

# 4-2 (결합 검증)
print('\n[4-2] 결합 결과:', 합계.shape)
print('결측 합계:', int(합계.isnull().sum().sum()), '건')
if len(합계) != 51 or 합계.isnull().any().any():
    print(합계.isnull().sum())
    raise ValueError('결합 결과에 행 수 또는 결측치 문제가 있습니다.')

# 4-3 (보조 범주)
합계['수도권여부'] = np.where(합계['시도명'].isin(['서울특별시', '인천광역시', '경기도']), '수도권', '비수도권')

# 4-4 (저장)
합계.to_csv(저장폴더 + '/결합테이블.csv', index=False, encoding='utf-8-sig')
print('[4-4] 결합 데이터 저장 완료:', 저장폴더 + '/결합테이블.csv')


# [5. 핵심 가설 판정 및 시각화]
# 5-1 (연도별 판정)
결과목록 = []
for 연도 in 연도들:
    자료 = 합계[합계['연도'] == 연도]
    정류장상관 = 자료['정류장_천명당'].corr(자료['반납률'])
    고령화상관 = 자료['고령화율'].corr(자료['반납률'])
    사고상관 = 자료['반납률'].corr(자료['고령사고_만명당'])
    조건1 = 정류장상관 >= 0.4
    조건2 = abs(정류장상관) > abs(고령화상관)
    결과목록.append({'연도': 연도,
                 '정류장_반납률_r': 정류장상관, '고령화율_반납률_r': 고령화상관, '반납률_사고_r': 사고상관,
                 '①r≥0.4': 조건1, '②|정류장|>|고령화|': 조건2, '핵심가설충족': 조건1 and 조건2,
                 'A_H3충족': 사고상관 <= -0.4})
판정표 = pd.DataFrame(결과목록)
print('\n[5-1] 연도별 가설 판정')
print(판정표.round(3).to_string(index=False))

충족연도수 = 판정표['핵심가설충족'].sum()
최종판정 = '채택' if 충족연도수 == 3 else '부분 채택' if 충족연도수 == 2 else '기각'
print('핵심 가설 최종 판정:', 최종판정, f'({충족연도수}/3개 연도 만족)')

# 5-3 (보조 가설 - 코로나): 관계의 '세기' 는 절댓값으로 비교 (r 이 음수일 때 r2022 < r2024 는 거꾸로 나옴)
r2022 = 판정표.loc[판정표['연도'] == 2022, '정류장_반납률_r'].iloc[0]
r2024 = 판정표.loc[판정표['연도'] == 2024, '정류장_반납률_r'].iloc[0]
보조충족 = abs(r2022) < abs(r2024)
print(f'\n[5-3] 코로나 보조 가설 (|r2022| < |r2024|): |{r2022:.3f}| < |{r2024:.3f}| → {보조충족} → {"채택" if 보조충족 else "기각"}')
if r2022 < 0 and r2024 < 0:
    print('      ※ r 이 음수라 "일상 회복 이후 버스의 역할이 커졌다" 는 해석의 전제(양의 관계)부터 성립하지 않음')

# 5-4 (이상치 시도 제외 시 r)
print('\n[5-4] 이상치 시도 제외 시 r(정류장_천명당, 반납률)')
for 제외 in ['세종특별자치시', '제주특별자치도']:
    for 연도 in 연도들:
        자료 = 합계[(합계['연도'] == 연도) & (합계['시도명'] != 제외)]
        print(f'  {제외} 제외 {연도}: r = {자료["정류장_천명당"].corr(자료["반납률"]):.3f}')

# 5-5 (A 가설 3)
print('\n[5-5] A 가설 3 (3개 연도 모두 r(반납률, 고령사고_만명당) ≤ -0.4 이면 채택):',
      '채택' if 판정표['A_H3충족'].all() else '기각')

판정표.to_csv(저장폴더 + '/가설판정표.csv', index=False, encoding='utf-8-sig')

# 그래프 ① 핵심 가설 – 연도별 상관계수 비교 막대
#   정류장 r 과 고령화율 r 을 연도별로 나란히 놓는다.
#   조건 ① 정류장 막대가 +0.4 선 위에 있는가 / 조건 ② 정류장 막대가 고령화율 막대보다 긴가
x = np.arange(len(연도들))
폭 = 0.36
fig, ax = plt.subplots(figsize=(9, 5.5))
ax.axhspan(-0.4, 0.4, color='lightgray', alpha=0.5, label='약한 상관 (|r| < 0.4)')
ax.axhline(0, color='gray', linewidth=0.8)
막대1 = ax.bar(x - 폭 / 2, 판정표['정류장_반납률_r'], 폭, color='#1F4E79', label='정류장_천명당')
막대2 = ax.bar(x + 폭 / 2, 판정표['고령화율_반납률_r'], 폭, color='#9AA5B1', label='고령화율')
ax.bar_label(막대1, fmt='%.2f', padding=3, fontsize=11)
ax.bar_label(막대2, fmt='%.2f', padding=3, fontsize=11)
ax.set_xticks(x, [str(y) for y in 연도들])
ax.set_ylim(-1, 1)
ax.set_ylabel('반납률과의 상관계수 r')
ax.set_title('연도별 반납률과의 상관계수', fontsize=13, fontweight='bold')
ax.legend(loc='upper right')
plt.tight_layout()
plt.savefig(그래프폴더 + '/핵심가설-1_E가설2_연도별_상관계수_막대.png', dpi=150)
plt.show()

# 그래프 ② 정류장 3그룹 평균 반납률 막대
#   17개 시도를 정류장_천명당 순으로 하위·중위·상위 3그룹(6·5·6곳)으로 나눠 그룹별 평균 반납률을 비교한다.
#   (B 의 고령화율 3그룹 막대와 같은 형식 → 고령화율은 평평, 정류장은 계단)
fig, axs = plt.subplots(1, 3, figsize=(16, 5.5), sharey=True)
for ax, 연도 in zip(axs, 연도들):
    t = 합계[합계['연도'] == 연도].copy()
    t['그룹'] = pd.qcut(t['정류장_천명당'], 3, labels=['하위', '중위', '상위'])
    그룹표 = t.groupby('그룹', observed=True).agg(평균반납률=('반납률', 'mean'), 시도수=('시도명', 'count'),
                                              최소=('정류장_천명당', 'min'), 최대=('정류장_천명당', 'max'))
    라벨 = [f"정류장 {그룹}\n({행.최소:.1f}~{행.최대:.1f}개, {int(행.시도수)}곳)" for 그룹, 행 in 그룹표.iterrows()]
    막대 = ax.bar(라벨, 그룹표['평균반납률'], color=연도색[연도], width=0.6)
    ax.bar_label(막대, fmt='%.2f', padding=3, fontsize=11)
    r = 판정표.loc[판정표['연도'] == 연도, '정류장_반납률_r'].iloc[0]
    ax.set_title(f'{연도}년  r = {r:.2f}', fontsize=12)
    ax.set_ylim(0, 합계['반납률'].max())
    ax.set_ylabel('평균 반납률' if 연도 == 연도들[0] else '')
    ax.tick_params(axis='x', labelsize=9)
    ax.grid(axis='x', visible=False)
    print(f'[그래프 ②] {연도} 정류장 3그룹 평균 반납률:', 그룹표['평균반납률'].round(2).to_dict())
fig.suptitle('정류장 수 3그룹별 평균 반납률', fontsize=14, fontweight='bold')
plt.tight_layout()
plt.savefig(그래프폴더 + '/핵심가설-2_정류장_3그룹_막대.png', dpi=150)
plt.show()

# 그래프 ③ A 가설 3 – 연도별 반납률 · 고령사고 상관계수 막대
plt.figure(figsize=(8, 5))
plt.axhspan(-0.4, 0.4, color='lightgray', alpha=0.5, label='약한 상관 (|r| < 0.4)')
plt.axhline(0, color='gray', linewidth=0.8)
막대 = plt.bar([str(y) for y in 연도들], 판정표['반납률_사고_r'], color=[연도색[y] for y in 연도들], width=0.5)
plt.bar_label(막대, labels=[f'r = {v:.2f}' for v in 판정표['반납률_사고_r']], padding=4, fontsize=11)
plt.ylim(-1, 1)
plt.ylabel('상관계수 r')
plt.title('연도별 반납률 · 고령사고 상관계수', fontsize=13, fontweight='bold')
plt.legend(loc='upper right')
plt.tight_layout()
plt.savefig(그래프폴더 + '/E가설1_반납률_고령사고_상관계수_막대.png', dpi=150)
plt.show()

